/**
 * v7: passes the serialized alarm payload to AlarmSoundService so the native
 * wake activity can deep-link directly to /alarm-ring.
 *
 * v6: the alarm full-screen UI is now driven by AlarmSoundService's foreground
 * full-screen alarm notification, with Expo's notification still posted for
 * action/listener compatibility.
 *
 * v5: the alarm full-screen UI is now driven entirely by the notification's
 * full-screen intent (see ExpoNotificationBuilder.kt v10), which targets the
 * always-present NotificationForwarderActivity -> MainActivity chain.
 *
 * The previous versions tried to start `.AlarmWakeActivity` directly from the
 * AlarmManager broadcast. That class is generated by a config plugin and was
 * missing from the compiled APK, so the launch threw ActivityNotFoundException
 * (silently caught) and the alarm only showed a banner. Starting an activity
 * from a background broadcast is also unreliable on Android 14+, whereas the
 * full-screen intent is the platform-sanctioned path for alarms.
 *
 * triggerNotification now just (1) starts the alarm sound foreground service if
 * present and (2) posts the notification, whose FSI does the lock-screen
 * takeover.
 */
const TRIGGER_REPLACEMENT = `  override fun triggerNotification(identifier: String) {
    try {
      val notificationRequest: NotificationRequest = store.getNotificationRequest(identifier)!!
      // Ripple alarm scheduling v7 — start native alarm FSI service, then post Expo notification.
      if (identifier.startsWith("ripple_alarm_fire_")) {
        try {
          val svcIntent = android.content.Intent().apply {
            setClassName(context.packageName, context.packageName + ".AlarmSoundService")
            putExtra("soundName", notificationRequest.content.soundName ?: "")
            putExtra("alarmTitle", notificationRequest.content.title ?: "Alarm")
            putExtra("alarmBody", notificationRequest.content.text ?: "Ringing")
            putExtra("alarmIdentifier", identifier)
            putExtra("alarmPayload", notificationRequest.content.body?.toString() ?: "")
          }
          if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.O) {
            context.startForegroundService(svcIntent)
          } else {
            context.startService(svcIntent)
          }
        } catch (e: Exception) {
          Log.w("expo-notifications", "Ripple AlarmSoundService start skipped: " + e.message)
        }
      }
      NotificationsService.receive(context, Notification(notificationRequest))
      NotificationsService.schedule(context, notificationRequest)
    } catch (e: ClassNotFoundException) {
      Log.e("expo-notifications", "An exception occurred while triggering notification " + identifier + ", removing. " + e.message)
      e.printStackTrace()
      NotificationsService.removeScheduledNotification(context, identifier)
    } catch (e: InvalidClassException) {
      Log.e("expo-notifications", "An exception occurred while triggering notification " + identifier + ", removing. " + e.message)
      e.printStackTrace()
      NotificationsService.removeScheduledNotification(context, identifier)
    } catch (e: NullPointerException) {
      Log.e("expo-notifications", "An exception occurred while triggering notification " + identifier + ", removing. " + e.message)
      e.printStackTrace()
      NotificationsService.removeScheduledNotification(context, identifier)
    }
  }`;

const SETUP_ALARM_REPLACEMENT = `  private fun setupAlarm(triggerAtMillis: Long, operation: PendingIntent, identifier: String = "") {
    // Ripple alarm scheduling v7 — register alarm fires as system alarm-clock alarms.
    // This shows the OS alarm icon and grants the temporary power allowlist that lets
    // the full-screen intent fire reliably. The showIntent opens the app's MainActivity
    // (always present) — never a plugin-generated activity that might be missing.
    if (identifier.startsWith("ripple_alarm_fire_") && Build.VERSION.SDK_INT >= Build.VERSION_CODES.LOLLIPOP) {
      try {
        val showLaunch = context.packageManager.getLaunchIntentForPackage(context.packageName)?.apply {
          addFlags(android.content.Intent.FLAG_ACTIVITY_NEW_TASK or android.content.Intent.FLAG_ACTIVITY_SINGLE_TOP)
          putExtra("rippleAlarmFullScreen", true)
        }
        if (showLaunch != null) {
          val showFlags = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
          } else {
            PendingIntent.FLAG_UPDATE_CURRENT
          }
          val showRequestCode = ("ripple_alarm_clock_show_" + identifier).hashCode()
          val showIntent = PendingIntent.getActivity(context, showRequestCode, showLaunch, showFlags)
          val alarmClockInfo = AlarmManager.AlarmClockInfo(triggerAtMillis, showIntent)
          alarmManager.setAlarmClock(alarmClockInfo, operation)
          return
        }
      } catch (e: Exception) {
        Log.w("expo-notifications", "Ripple alarm: setAlarmClock failed for " + identifier + ", falling back: " + e.message)
      }
    }
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S || alarmManager.canScheduleExactAlarms()) {
      AlarmManagerCompat.setExactAndAllowWhileIdle(
        alarmManager,
        AlarmManager.RTC_WAKEUP,
        triggerAtMillis,
        operation
      )
    } else {
      AlarmManagerCompat.setAndAllowWhileIdle(
        alarmManager,
        AlarmManager.RTC_WAKEUP,
        triggerAtMillis,
        operation
      )
    }
  }`;

